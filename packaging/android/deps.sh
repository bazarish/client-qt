#!/bin/bash
# Bazarish project (c) 2026
# The libraries the client links that Qt for Android does not carry, built for one
# ABI into one prefix. Each stage is skipped once its mark exists in the prefix.
set -eu -o pipefail

readonly kJobs=4
readonly kApi=28
readonly kAbi=arm64-v8a
readonly kTriple=aarch64-linux-android
readonly kOpenSsl=3.5.7
readonly kBoost=1.87.0
readonly kSqlCipher=4.19.0
readonly kOpus=1.5.2
readonly kQrencode=4.1.1

readonly kNdk=${ANDROID_NDK_ROOT:?the NDK, as ANDROID_NDK_ROOT}
readonly kPrefix=${1:?usage: deps.sh <prefix> <work dir>}
readonly kWork=${2:?usage: deps.sh <prefix> <work dir>}
readonly kToolchain=$kNdk/toolchains/llvm/prebuilt/linux-x86_64
readonly kCc=$kToolchain/bin/$kTriple$kApi-clang
readonly kCxx=$kToolchain/bin/$kTriple$kApi-clang++
readonly kAr=$kToolchain/bin/llvm-ar
readonly kCmakeAndroid=(
    -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$kPrefix"
    -DCMAKE_TOOLCHAIN_FILE="$kNdk/build/cmake/android.toolchain.cmake"
    -DANDROID_ABI="$kAbi" -DANDROID_PLATFORM="android-$kApi" -DBUILD_SHARED_LIBS=OFF
)

mkdir -p "$kPrefix/lib" "$kPrefix/include" "$kWork"

step() {
    if [ -f "$kPrefix/.$1" ]; then
        echo "== $1 already built"
        return 1
    fi
    echo "== $1"
    return 0
}

done_with() {
    touch "$kPrefix/.$1"
}

fetch() {
    test -f "$kWork/$2" && return 0
    curl -fsSL -o "$kWork/$2.part" "$1"
    mv "$kWork/$2.part" "$kWork/$2"
}

unpack() {
    cd "$kWork" && rm -rf "$2" && tar xf "$1" && cd "$2"
}

if step openssl; then
    fetch "https://github.com/openssl/openssl/releases/download/openssl-$kOpenSsl/openssl-$kOpenSsl.tar.gz" \
        "openssl-$kOpenSsl.tar.gz"
    unpack "openssl-$kOpenSsl.tar.gz" "openssl-$kOpenSsl"
    # No configuration file is read at run time: the path it would be read from is
    # this build machine's, not the phone's.
    PATH="$kToolchain/bin:$PATH" ./Configure android-arm64 -D__ANDROID_API__=$kApi \
        no-shared no-docs no-tests no-autoload-config \
        --prefix="$kPrefix" --openssldir="$kPrefix/ssl" --libdir=lib
    PATH="$kToolchain/bin:$PATH" make -j"$kJobs" build_libs
    PATH="$kToolchain/bin:$PATH" make install_dev
    cd "$kWork" && rm -rf "openssl-$kOpenSsl"
    done_with openssl
fi

if step boost; then
    fetch "https://archives.boost.io/release/$kBoost/source/boost_${kBoost//./_}.tar.bz2" \
        "boost-$kBoost.tar.bz2"
    unpack "boost-$kBoost.tar.bz2" "boost_${kBoost//./_}"
    ./bootstrap.sh --with-libraries=program_options
    cat > android-config.jam <<EOF
using clang : android : $kCxx : <archiver>$kAr <ranlib>$kToolchain/bin/llvm-ranlib ;
EOF
    ./b2 -j"$kJobs" --user-config=android-config.jam toolset=clang-android target-os=android \
        architecture=arm address-model=64 binary-format=elf abi=aapcs \
        link=static threading=multi variant=release cxxflags=-fPIC --with-program_options \
        --prefix="$kPrefix" install
    cd "$kWork" && rm -rf "boost_${kBoost//./_}"
    done_with boost
fi

if step opus; then
    fetch "https://downloads.xiph.org/releases/opus/opus-$kOpus.tar.gz" "opus-$kOpus.tar.gz"
    unpack "opus-$kOpus.tar.gz" "opus-$kOpus"
    cmake -S . -B build "${kCmakeAndroid[@]}" -DOPUS_BUILD_PROGRAMS=OFF -DOPUS_BUILD_TESTING=OFF
    cmake --build build -j "$kJobs"
    cmake --install build
    cd "$kWork" && rm -rf "opus-$kOpus"
    done_with opus
fi

if step qrencode; then
    fetch "https://github.com/fukuchi/libqrencode/archive/refs/tags/v$kQrencode.tar.gz" \
        "qrencode-$kQrencode.tar.gz"
    unpack "qrencode-$kQrencode.tar.gz" "libqrencode-$kQrencode"
    # Its CMakeLists asks for a policy version this CMake no longer accepts.
    cmake -S . -B build "${kCmakeAndroid[@]}" -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
        -DWITH_TOOLS=NO -DWITH_TESTS=NO
    cmake --build build -j "$kJobs"
    cmake --install build
    cd "$kWork" && rm -rf "libqrencode-$kQrencode"
    done_with qrencode
fi

if step sqlcipher; then
    fetch "https://github.com/sqlcipher/sqlcipher/archive/refs/tags/v$kSqlCipher.tar.gz" \
        "sqlcipher-$kSqlCipher.tar.gz"
    unpack "sqlcipher-$kSqlCipher.tar.gz" "sqlcipher-$kSqlCipher"
    # The amalgamation is generated by tools that run here, so this configure is for
    # this machine; the one C file it yields is then compiled for the phone.
    ./configure --with-tempstore=yes
    make sqlite3.c
    "$kCc" -c sqlite3.c -o sqlite3.o -O2 -fPIC -I"$kPrefix/include" \
        -DSQLITE_HAS_CODEC -DSQLCIPHER_CRYPTO_OPENSSL -DSQLITE_TEMP_STORE=2 \
        -DSQLITE_THREADSAFE=1 -DSQLITE_EXTRA_INIT=sqlcipher_extra_init \
        -DSQLITE_EXTRA_SHUTDOWN=sqlcipher_extra_shutdown
    "$kAr" rcs "$kPrefix/lib/libsqlcipher.a" sqlite3.o
    mkdir -p "$kPrefix/include/sqlcipher"
    cp sqlite3.h sqlite3ext.h "$kPrefix/include/sqlcipher/"
    cd "$kWork" && rm -rf "sqlcipher-$kSqlCipher"
    done_with sqlcipher
fi

echo "== the prefix"
ls "$kPrefix/lib"
